-- Compatible with existing deployments where JPA has already created the tables.
-- On a fresh DB, Flyway runs before Hibernate; marketplace_offers exists upfront.
CREATE TABLE IF NOT EXISTS marketplace_offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(32) NOT NULL UNIQUE,
  title varchar(90) NOT NULL,
  description varchar(300),
  kind varchar(16) NOT NULL,
  value numeric(12,2) NOT NULL,
  min_subtotal numeric(12,2) NOT NULL DEFAULT 0,
  max_subtotal numeric(12,2),
  max_discount numeric(12,2),
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  global_limit integer NOT NULL DEFAULT 100000,
  per_customer_limit integer NOT NULL DEFAULT 1,
  used_count integer NOT NULL DEFAULT 0,
  auto_apply boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT marketplace_offers_value_positive CHECK (value > 0),
  CONSTRAINT marketplace_offers_range CHECK (ends_at > starts_at),
  CONSTRAINT marketplace_offers_redemptions CHECK (used_count >= 0)
);
CREATE INDEX IF NOT EXISTS marketplace_offers_active_threshold ON marketplace_offers (active,min_subtotal);
ALTER TABLE IF EXISTS carts ADD COLUMN IF NOT EXISTS coupon_code varchar(32);
ALTER TABLE IF EXISTS orders ADD COLUMN IF NOT EXISTS order_subtotal double precision;
ALTER TABLE IF EXISTS orders ADD COLUMN IF NOT EXISTS discount_amount double precision;
ALTER TABLE IF EXISTS orders ADD COLUMN IF NOT EXISTS offer_code varchar(32);
ALTER TABLE IF EXISTS stripe_checkout_attempts ADD COLUMN IF NOT EXISTS offer_code varchar(32);
ALTER TABLE IF EXISTS stripe_checkout_attempts ADD COLUMN IF NOT EXISTS discount_paise bigint;
